package com.example.uniproject.data.model.category;

public final class CategoryResponse {
    private Long id;
    private String name;
    private String description;

    public CategoryResponse() {
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }
}
